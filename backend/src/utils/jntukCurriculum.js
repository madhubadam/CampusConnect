/**
 * Returns curriculum metadata for a given semester or regulation
 */
export function getCurriculumForSemester(semCode, regulation = 'R20') {
  const norm = String(semCode).trim().toUpperCase();
  const map = JNTUK_R20_CSE_CURRICULUM;
  for (const [key, val] of Object.entries(map)) {
    if (key.toUpperCase() === norm) return val;
  }
  return null;
}
