/**
 * Converts raw datasets into normalized student objects
 * Stores only student names and registration numbers without invented attributes
 */
export function getAuthoritativeStudents() {
  const students = [];
  const seenRegs = new Set();

  function processSection(rawList, sectionName) {
    rawList.forEach(([regNum, name]) => {
      const reg = String(regNum).trim();
      const studentName = String(name).trim();
      
      // Idempotency: prevent duplicates
      if (seenRegs.has(reg)) {
        console.warn(`[Student Seed Warning] Duplicate registration number detected: ${reg} (${studentName}). Skipping.`);
        return;
      }
      seenRegs.add(reg);

      students.push({
        id: reg,
        registrationNumber: reg,
        rollNumber: reg, // Alias for API compatibility
        name: studentName,
        section: sectionName,
        academicYear: '3rd Year',
        department: 'CSE',
        enrollmentStatus: 'Active'
      });
    });
  }

  processSection(SECTION_A_RAW, '3rd Year Section A');
  processSection(SECTION_B_RAW, '3rd Year Section B');
  processSection(SECTION_C_RAW, '3rd Year Section C');

  return students;
}
